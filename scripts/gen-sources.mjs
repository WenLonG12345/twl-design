// Scans motions/<slug>/ and generates:
//   motions/registry.generated.ts     every meta.ts, so new motions need no manual registration
//   motions/demos.generated.tsx       slug → Demo component map for the client
//   motions/sources.generated.json    each motion's source, shown on its detail page
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'

const sourceFiles = ['Demo.tsx', 'demo.module.css']
const slugs = (await readdir('motions', { withFileTypes: true }))
  .filter((d) => d.isDirectory() && existsSync(`motions/${d.name}/meta.ts`) && existsSync(`motions/${d.name}/Demo.tsx`))
  .map((d) => d.name)
  .sort()

const ident = (slug) => slug.replace(/-(\w)/g, (_, c) => c.toUpperCase())
const header = '// Generated by scripts/gen-sources.mjs. Do not edit.\n'

await writeFile(
  'motions/registry.generated.ts',
  header +
    "import type { Motion } from '@/lib/motions'\n" +
    slugs.map((s) => `import ${ident(s)} from './${s}/meta'`).join('\n') +
    `\n\nexport const registry: Motion[] = [${slugs.map(ident).join(', ')}]\n`,
)

await writeFile(
  'motions/demos.generated.tsx',
  header +
    "'use client'\n\n" +
    slugs.map((s) => `import ${ident(s)} from './${s}/Demo'`).join('\n') +
    '\n\nexport const demos: Record<string, React.ComponentType<{ labels: Record<string, string> }>> = {\n' +
    slugs.map((s) => `  '${s}': ${ident(s)},`).join('\n') +
    '\n}\n',
)

const sources = {}
for (const s of slugs) {
  sources[s] = []
  for (const name of sourceFiles) {
    const p = `motions/${s}/${name}`
    if (existsSync(p)) sources[s].push({ name, code: await readFile(p, 'utf8') })
  }
}
await writeFile('motions/sources.generated.json', JSON.stringify(sources, null, 2) + '\n')
console.log(`gen-sources: ${slugs.length} motions`)
